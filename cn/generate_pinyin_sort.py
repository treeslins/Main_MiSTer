#!/usr/bin/env python3
"""Regenerate the checked-in pinyin index; requires pypinyin==0.55.0."""
from pathlib import Path
import struct

from pypinyin import Style, pinyin

ROOT = Path(__file__).resolve().parent
data = (ROOT / "assets/misterfpga.cn").read_bytes()
assert data[:8] == b"M16CN002"
count = struct.unpack_from("<I", data, 12)[0]
codes = [struct.unpack_from("<I", data, 16 + i * 40)[0] for i in range(count)]
entries = []
for cp in codes:
    if not (0x3400 <= cp <= 0x9FFF):
        continue
    reading = pinyin(chr(cp), style=Style.NORMAL, heteronym=False)[0][0]
    if reading.isascii() and reading.isalpha():
        entries.append((cp, reading.lower()))

syllables = sorted({reading for _, reading in entries})
ids = {reading: i for i, reading in enumerate(syllables)}
out = [
    "// Generated by cn/generate_pinyin_sort.py with pypinyin 0.55.0 (MIT).",
    "// Source: https://github.com/mozillazg/python-pinyin",
    "// Includes one default reading per glyph in the pinned Chinese OSD font.",
    "#pragma once",
    "#include <stdint.h>",
    "struct PinyinEntry { uint16_t codepoint; uint16_t syllable; };",
    f"static const char *const pinyin_syllables[{len(syllables)}] = {{",
]
out += [f'    "{word}",' for word in syllables]
out += ["};", f"static const PinyinEntry pinyin_entries[{len(entries)}] = {{"]
out += [f"    {{0x{cp:04X}, {ids[reading]}}}," for cp, reading in entries]
out += ["};", ""]
(ROOT / "pinyin_sort_data.h").write_text("\n".join(out), encoding="utf-8")
